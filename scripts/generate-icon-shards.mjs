// Generates the editor icon catalog as small, alphabetized shards. The reader
// only loads the shard that contains a requested icon, and the picker streams
// shards in as they arrive. Run `npm run icons:generate` after upgrading
// Font Awesome so the imports and name ranges stay in sync.
import {mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync} from "node:fs";
import {join} from "node:path";
import {fileURLToPath} from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const styles = [
  {name: "solid", pkg: "free-solid-svg-icons", groups: [["0", "c"], ["d", "h"], ["i", "p"], ["q", "z"]]},
  {name: "regular", pkg: "free-regular-svg-icons", groups: [["0", "z"]]},
  {name: "brands", pkg: "free-brands-svg-icons", groups: [["0", "m"], ["n", "z"]]},
];
const output = join(root, "components", "icon-catalog");

function readIcons(style) {
  const dir = join(root, "node_modules", "@fortawesome", style.pkg);
  const icons = new Map();
  for (const file of readdirSync(dir).filter((name) => /^fa[A-Za-z0-9]+\.js$/.test(name)).sort()) {
    const source = readFileSync(join(dir, file), "utf8");
    const iconName = source.match(/var iconName = '([^']+)'/)?.[1];
    const exported = source.match(/exports\.(fa\w+) = exports\.definition/)?.[1];
    if (!iconName || !exported || icons.has(iconName)) continue;
    icons.set(iconName, {iconName, exported, module: file.slice(0, -3)});
  }
  return [...icons.values()];
}

function shardIcons(icons, groups) {
  const buckets = groups.map(([from, to]) => ({from, to, chars: "", icons: []}));
  for (const icon of icons) {
    const first = icon.iconName[0];
    const bucket = buckets.find((item) => first >= item.from && first <= item.to) ?? buckets.at(-1);
    if (!bucket.chars.includes(first)) bucket.chars += first;
    bucket.icons.push(icon);
  }
  return buckets.filter((bucket) => bucket.icons.length);
}

rmSync(output, {recursive: true, force: true});
mkdirSync(output, {recursive: true});

const manifestShards = [];
let version = "";
for (const style of styles) {
  const icons = readIcons(style);
  if (!version) {
    version = JSON.parse(
      readFileSync(join(root, "node_modules", "@fortawesome", style.pkg, "package.json"), "utf8"),
    ).version;
  }
  const shards = shardIcons(icons, style.groups);
  const loaders = [];
  for (const shard of shards) {
    const name = `${style.name}-${shard.from}-${shard.to}`;
    // Import each icon from its own module so the production build only ships
    // the shard's glyphs instead of a shared Font Awesome vendor chunk.
    const imports = shard.icons
      .map((icon) => `import {${icon.exported}} from "@fortawesome/${style.pkg}/${icon.module}";`)
      .join("\n");
    const entries = shard.icons
      .map((icon) => `  {style: "${style.name}", icon: ${icon.exported}},`)
      .join("\n");
    writeFileSync(
      join(output, `${name}.ts`),
      `// Generated by scripts/generate-icon-shards.mjs from Font Awesome ${version}. Do not edit.\n${imports}\nimport type {CatalogIcon} from "../icon-catalog-types";\n\nexport const icons: CatalogIcon[] = [\n${entries}\n];\n`,
    );
    loaders.push(
      `    {chars: "${shard.chars}", load: () => import("./icon-catalog/${name}").then((module) => module.icons)},`,
    );
  }
  manifestShards.push(`  ${style.name}: [\n${loaders.join("\n")}\n  ],`);
}

writeFileSync(
  join(root, "components", "icon-catalog.ts"),
  `// Generated by scripts/generate-icon-shards.mjs from Font Awesome ${version}. Do not edit.
import type {CatalogIcon} from "./icon-catalog-types";
import {customIcons} from "./icon-custom";

export type {CatalogIcon} from "./icon-catalog-types";

type Shard = {
  chars: string;
  load: () => Promise<CatalogIcon[]>;
};

const shards: Record<string, Shard[]> = {
${manifestShards.join("\n")}
};

const customCatalog: CatalogIcon[] = customIcons.flatMap((icon) =>
  icon.styles.map((style) => ({
    style,
    icon: {iconName: icon.iconName, icon: icon.icon},
  })),
);

const cache = new Map<string, Promise<CatalogIcon[]>>();

function loadShard(style: string, shard: Shard) {
  const key = style + ":" + shard.chars;
  let pending = cache.get(key);
  if (!pending) {
    pending = shard.load().catch((error) => {
      cache.delete(key);
      throw error;
    });
    cache.set(key, pending);
  }
  return pending;
}

function shardFor(style: string, name: string) {
  const first = name.trim().charAt(0).toLowerCase();
  return shards[style]?.find((shard) => shard.chars.includes(first));
}

export function loadIcon(style: string, name: string): Promise<CatalogIcon[]> {
  const shard = shardFor(style, name);
  return shard ? loadShard(style, shard) : Promise.resolve([]);
}

export function loadStyle(
  style: string,
  onShard?: (icons: CatalogIcon[]) => void,
): Promise<void> {
  const custom = customCatalog.filter((icon) => icon.style === style);
  if (custom.length) onShard?.(custom);
  const list = shards[style];
  if (!list) return Promise.resolve();
  return Promise.all(
    list.map(async (shard) => {
      const icons = await loadShard(style, shard);
      onShard?.(icons);
    }),
  ).then(() => undefined);
}
`,
);
